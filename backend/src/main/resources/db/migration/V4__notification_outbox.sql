-- Outbox: notifications are stored before they are sent (ADR 0004). One row per
-- shift, member, and type, so repeated scheduler runs can never enqueue duplicates.
CREATE TABLE notification (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id bigint NOT NULL REFERENCES shift(id) ON DELETE CASCADE,
    member_id bigint NOT NULL REFERENCES member(id),
    type text NOT NULL CHECK (type IN ('REMINDER', 'NUDGE', 'GROUP_ALERT')),
    status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    last_error text,
    -- When the next send attempt is due; NULL means no further attempts.
    next_attempt_at timestamptz,
    created_at timestamptz NOT NULL,
    sent_at timestamptz,
    CONSTRAINT notification_once UNIQUE (shift_id, member_id, type),
    CHECK (status <> 'SENT' OR sent_at IS NOT NULL)
);
CREATE INDEX notification_due ON notification (next_attempt_at) WHERE status IN ('PENDING', 'FAILED');

-- Local dates and wall-clock times follow America/Chicago. Weekdays use ISO 1–7.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE member (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (btrim(name) <> ''),
    email text NOT NULL CHECK (btrim(email) <> ''),
    uark_email text,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX member_email_unique ON member (lower(email));
CREATE UNIQUE INDEX member_uark_email_unique ON member (lower(uark_email));

CREATE TABLE room (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (btrim(code) <> ''),
    name text NOT NULL CHECK (btrim(name) <> ''),
    capacity integer CHECK (capacity > 0),
    type text,
    active boolean NOT NULL DEFAULT true
);

-- A missing weekday means closed/unknown. Midnight closing uses 24:00.
CREATE TABLE library_hours (
    weekday smallint PRIMARY KEY CHECK (weekday BETWEEN 1 AND 7),
    opens_at time NOT NULL,
    closes_at time NOT NULL,
    CHECK (closes_at > opens_at)
);

CREATE TABLE member_unavailability (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL REFERENCES member(id),
    kind text NOT NULL CHECK (kind IN ('ONE_TIME', 'WEEKLY')),
    date date,
    weekday smallint CHECK (weekday BETWEEN 1 AND 7),
    valid_from date,
    valid_until date,
    start_time time NOT NULL,
    end_time time NOT NULL,
    CHECK (end_time > start_time),
    CHECK (valid_until IS NULL OR (valid_from IS NOT NULL AND valid_until >= valid_from)),
    CHECK ((kind = 'ONE_TIME' AND date IS NOT NULL AND weekday IS NULL
                AND valid_from IS NULL AND valid_until IS NULL)
        OR (kind = 'WEEKLY' AND date IS NULL AND weekday IS NOT NULL AND valid_from IS NOT NULL))
);
CREATE INDEX member_unavailability_member_idx ON member_unavailability(member_id);

CREATE TABLE study_block (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('ONE_TIME', 'WEEKLY')),
    date date,
    weekday smallint CHECK (weekday BETWEEN 1 AND 7),
    valid_from date,
    valid_until date,
    start_time time NOT NULL,
    end_time time NOT NULL,
    preferred_room_id bigint NOT NULL REFERENCES room(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (end_time > start_time),
    CHECK (extract(epoch FROM start_time)::numeric % 900 = 0
        AND extract(epoch FROM end_time)::numeric % 900 = 0),
    CHECK (valid_until IS NULL OR (valid_from IS NOT NULL AND valid_until >= valid_from)),
    CHECK ((kind = 'ONE_TIME' AND date IS NOT NULL AND weekday IS NULL
                AND valid_from IS NULL AND valid_until IS NULL)
        OR (kind = 'WEEKLY' AND date IS NULL AND weekday IS NOT NULL AND valid_from IS NOT NULL))
);

CREATE TABLE study_block_backup_room (
    study_block_id bigint NOT NULL REFERENCES study_block(id) ON DELETE CASCADE,
    room_id bigint NOT NULL REFERENCES room(id),
    priority integer NOT NULL CHECK (priority > 0),
    PRIMARY KEY (study_block_id, room_id),
    UNIQUE (study_block_id, priority)
);

CREATE TABLE shift (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_block_id bigint NOT NULL REFERENCES study_block(id),
    member_id bigint REFERENCES member(id),
    planned_room_id bigint NOT NULL REFERENCES room(id),
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    local_date date GENERATED ALWAYS AS ((starts_at AT TIME ZONE 'America/Chicago')::date) STORED,
    status text NOT NULL DEFAULT 'UNASSIGNED'
        CHECK (status IN ('UNASSIGNED', 'ASSIGNED', 'BOOKED', 'MISSED', 'CANCELLED')),
    booked_room_id bigint REFERENCES room(id),
    booked_at timestamptz,
    libcal_cancel_required boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT shift_duration CHECK (ends_at > starts_at AND ends_at - starts_at <= interval '4 hours'),
    CONSTRAINT shift_quarter_hour CHECK (
        extract(epoch FROM starts_at)::numeric % 900 = 0
        AND extract(epoch FROM ends_at)::numeric % 900 = 0),
    CONSTRAINT shift_assignment_state CHECK (
        (status <> 'UNASSIGNED' OR member_id IS NULL)
        AND (status NOT IN ('ASSIGNED', 'BOOKED') OR member_id IS NOT NULL)),
    CONSTRAINT shift_booking_details CHECK (
        status <> 'BOOKED' OR (booked_room_id IS NOT NULL AND booked_at IS NOT NULL)),
    CONSTRAINT shift_block_start_unique UNIQUE (study_block_id, starts_at),
    CONSTRAINT shift_member_no_overlap EXCLUDE USING gist (
        member_id WITH =, tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status IN ('ASSIGNED', 'BOOKED'))
);
CREATE UNIQUE INDEX shift_member_local_day_unique ON shift(member_id, local_date)
    WHERE status IN ('ASSIGNED', 'BOOKED');
CREATE INDEX shift_starts_at_idx ON shift(starts_at);

-- Preserve created_at and maintain updated_at for every write, including direct SQL.
CREATE FUNCTION update_shift_timestamp() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.created_at := OLD.created_at;
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;
CREATE TRIGGER shift_updated_at BEFORE UPDATE ON shift
    FOR EACH ROW EXECUTE FUNCTION update_shift_timestamp();
